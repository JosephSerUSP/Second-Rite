class Obj:
    def __init__(self, mtllib):
        self.lines = ["# generated by build_chapter.py from rooms.json", "mtllib " + mtllib]
        self.n = 0

    def box(self, mat, cx, cy, cz, sx, sy, sz):
        """World box (x right, y depth, z up), written OBJ Y-up like Blender."""
        self.lines.append("usemtl " + mat)
        hx, hy, hz = sx / 2, sy / 2, sz / 2
        for dx in (-hx, hx):
            for dy in (-hy, hy):
                for dz in (-hz, hz):
                    x, y, z = cx + dx, cy + dy, cz + dz
                    self.lines.append("v %.4f %.4f %.4f" % (x, z, -y))
        b = self.n
        # corner index = 1 + 4*ix + 2*iy + iz
        for f in ((0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)):
            self.lines.append("f " + " ".join(str(b + i + 1) for i in f))
        self.n += 8

    def write(self, path):
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(self.lines) + "\n")


def write_mtl(path, mats):
    out = ["# generated by build_chapter.py"]
    for name, kd in sorted(mats.items()):
        out += ["newmtl " + name, "Ka 1 1 1", "Kd %.3f %.3f %.3f" % tuple(kd), "Ks 0.1 0.1 0.1", "d 1", "illum 2", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))


def room_dims(room):
    w, d = room["size"]
    return w, d


def bounds_of(room):
    if room.get("corridor"):
        return dict(CORRIDOR_BOUNDS)
    w, d = room_dims(room)
    return {"minX": -w / 2 + 0.4, "maxX": w / 2 - 0.4, "minY": 0.3, "maxY": d - 0.4}


def door_point(room, door):
    b = bounds_of(room)
    wall, at = door["wall"], door["at"]
    return {"back": (at, b["maxY"]), "front": (at, b["minY"]),
            "left": (b["minX"], at), "right": (b["maxX"], at)}[wall]


def build_room_obj(room, mats):
    w, d = room_dims(room)
    pal = room["palette"]
    floor, wall, trim = PALETTES[pal]
    mats[pal + "_floor"], mats[pal + "_wall"], mats[pal + "_trim"] = floor, wall, trim
    mats["door_red"], mats["door_locked"] = [0.70, 0.08, 0.06], [0.25, 0.25, 0.28]
    o = Obj("blockout.mtl")
    o.box(pal + "_floor", 0, d / 2, -0.05, w, d, 0.1)
    o.box(pal + "_wall", 0, d + 0.1, 1.5, w + 0.4, 0.2, 3.0)            # back
    o.box(pal + "_wall", -w / 2 - 0.1, d / 2, 1.5, 0.2, d, 3.0)         # left
    o.box(pal + "_wall", w / 2 + 0.1, d / 2, 1.5, 0.2, d, 3.0)          # right
    o.box(pal + "_trim", 0, -0.05, 0.1, w + 0.4, 0.1, 0.2)              # front curb only
    for door in room["doors"]:
        x, y = door_point(room, door)
        mat = "door_locked" if door.get("needs") else "door_red"
        if door["wall"] == "back":
            o.box(mat, x, d, 1.1, 1.2, 0.1, 2.2)
        elif door["wall"] == "front":
            o.box(mat, x, 0.0, 0.03, 1.2, 0.6, 0.06)                     # threshold mat
        else:
            sx = -w / 2 if door["wall"] == "left" else w / 2
            o.box(mat, sx, y, 1.1, 0.1, 1.2, 2.2)
    path = os.path.join(BLOCKOUT, room["id"] + ".obj")
    o.write(path)
    return "assets/models/blockout/%s.obj" % room["id"]


