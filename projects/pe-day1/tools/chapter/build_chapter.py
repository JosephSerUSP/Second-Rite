def q(text):
    """A Formula string literal."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def setv(**kv):
    return {"cmd": "SET_SCENE_STATE", "assignments": [{"name": k, "value": v} for k, v in kv.items()]}


def iff(cond, then, other=None):
    out = {"cmd": "IF", "condition": cond, "then": then}
    if other:
        out["else"] = other
    return out


